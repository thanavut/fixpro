lines[hits[0]] = ('- ยืนยันบน production แล้ว (อ่านอย่างเดียว): sw.js = fixpro-v115 + APP_VERSION v115 + ระยะห่างบรรทัด'
    'ทุกหน้า desktop = มาตรฐานหน้าลูกค้า (computed: หัวเรื่อง 10px/ช่องค้นหา+ตัวกรอง 8px/ช่องค้นหา 458px ทุกหน้า) + '
    'desktop พื้น #E1E5EE ไร้เส้น v113/v114 คงอยู่ + dark ไม่พัง (rgb(15,17,23)) + mobile เดิมเป๊ะ (ค้นหา 119px เต็มแถว/'
    'mb 10px/body rgb(245,246,250)) + เมนูซ้ายการ์ดยาวขาว v111-v114 คงอยู่ + CSP ใหม่ v102 คงอยู่ + ข้อมูลจริงครบ '
    '(8 ลูกค้า 12 งาน), ไฟล์นี้เปิดได้ที่ https://fixpro-7b397.web.app/HANDOFF_FIXPRO.md')
t = '\n'.join(lines)

# 4) ข้อ 8 ประวัติ: แทรก v115 บนสุด
anchor = '- v114: **ลบเส้นแบ่ง + พื้นเข้มขึ้นอีกขั้น**'
