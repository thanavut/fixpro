"""handoff v115: บันทึกการจัดระยะห่างบรรทัดทุกหน้า desktop ให้เหมือนหน้า 'รายชื่อลูกค้า' + ช่องค้นหายาวเท่ากัน"""
p = '/home/z/my-project/fixpro/HANDOFF_FIXPRO.md'
