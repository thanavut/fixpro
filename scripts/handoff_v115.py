# 3) บรรทัดยืนยัน production (0.1 ท้าย) → v115
lines = t.split('\n')
hits = [i for i, l in enumerate(lines) if l.startswith('- ยืนยันบน production แล้ว (อ่านอย่างเดียว):')]
