# 1) หัวเอกสาร + สถานะ 0.1
assert 'production: **v114**' in t, 'เอกสารต้องอยู่สถานะ v114 ก่อน'
t = t.replace('production: **v114**', 'production: **v115**')
t = t.replace('- **งานถึง v114 เสร็จหมดแล้ว ไม่มีงานค้าง** — เวอร์ชันถัดไปที่ต้อง bump คือ **v115**',
              '- **งานถึง v115 เสร็จหมดแล้ว ไม่มีงานค้าง** — เวอร์ชันถัดไปที่ต้อง bump คือ **v116**')

